// Reproducible, offline build. Uses the exact compiler/OZ versions in package.json.
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import solc from "solc";

const root = process.cwd();
const sourceName = "contracts/mocks/MockTokens.sol";
const sources: Record<string, { content: string }> = {};
function collect(name: string) {
  if (sources[name]) return;
  const file = path.join(
    root,
    name.startsWith("@") ? "node_modules" : "",
    name
  );
  const content = fs.readFileSync(file, "utf8");
  sources[name] = { content };
  for (const match of content.matchAll(
    /import\s+(?:[^"']+from\s+)?["']([^"']+)["'];/g
  )) {
    collect(
      match[1].startsWith(".")
        ? path.posix.normalize(
            path.posix.join(path.posix.dirname(name), match[1])
          )
        : match[1]
    );
  }
}
if (solc.version() !== "0.8.28+commit.7893614a.Emscripten.clang")
  throw new Error("Expected solc 0.8.28");
if (
  JSON.parse(
    fs.readFileSync("node_modules/@openzeppelin/contracts/package.json", "utf8")
  ).version !== "5.0.2"
)
  throw new Error("Expected OpenZeppelin 5.0.2");
collect(sourceName);
const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    metadata: { bytecodeHash: "ipfs" },
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter(
  (e: { severity: string }) => e.severity === "error"
);
if (errors.length) throw new Error(JSON.stringify(errors));
const artifacts: Record<string, unknown> = {};
for (const standard of ["ERC20", "ERC721", "ERC1155"]) {
  const compiled = output.contracts[sourceName][`Mock${standard}`];
  artifacts[standard] = {
    contractName: `Mock${standard}`,
    abi: compiled.abi,
    bytecode: `0x${compiled.evm.bytecode.object}`,
    deployedBytecode: `0x${compiled.evm.deployedBytecode.object}`,
  };
}
const artifactsText =
  "// Generated by scripts/buildMockTokenArtifacts.ts; do not edit.\nexport const MOCK_ARTIFACTS = " +
  JSON.stringify(artifacts, null, 2) +
  " as const;\n" +
  `export const MOCK_COMPILER_VERSION = ${JSON.stringify(solc.version().split(".Emscripten")[0])};\n`;
const inputText = JSON.stringify(input, null, 2) + "\n";
const files = {
  "lib/mockTokens.generated.ts": artifactsText,
  "public/mock-tokens-standard-input.json": inputText,
};
for (const [file, text] of Object.entries(files)) {
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(file, "utf8") !== text)
      throw new Error(`Stale mock artifact: ${file}`);
  } else fs.writeFileSync(file, text);
  console.log(
    `${file} sha256=${createHash("sha256").update(text).digest("hex")}`
  );
}
