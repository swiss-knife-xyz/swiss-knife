const USDC = "0xA0b86991c6218b36c1d19D4a2e9Eb0cE3606eB48";

// Keep signature lookups offline: only the Universal Router selector is known.
const KNOWN_SIGNATURES: Record<string, string> = {
  "0x3593564c": "execute(bytes,bytes[],uint256)",
};

const mockFetch = async (input: string | URL | Request) => {
  const url = new URL(input instanceof Request ? input.url : input);
  if (url.host === "api.4byte.sourcify.dev") {
    const selector = url.searchParams.get("function") ?? "";
    const signature = KNOWN_SIGNATURES[selector];
    return Response.json({
      ok: true,
      result: {
        function: signature
          ? { [selector]: [{ name: signature, filtered: false }] }
          : {},
        event: {},
      },
    });
  }
  if (url.host === "www.4byte.directory") {
    return Response.json({ count: 0, results: [] });
  }
  throw new Error(`Unexpected network request: ${url}`);
};

before(() => {
  mock.method(globalThis, "fetch", mockFetch);
});

after(() => {
  mock.restoreAll();
});

test("nested abi-encoded bytes[] elements are decoded recursively (#161)", async () => {
  const result = await decodeRecursive({ calldata: ISSUE_161_CALLDATA });

  assert.ok(result);
  assert.equal(result.functionName, "execute");
  assert.equal(result.args[1].type, "bytes[]");
  const inputs = result.args[1].value as DecodeArrayParamResult;
  assert.equal(inputs.length, 4);

  const decodedInputs = inputs.map(
    (input) => (input.value as DecodeBytesParamResult).decoded
  );
  for (const decoded of decodedInputs) {
    assert.equal(decoded?.signature, "abi.encode");
  }

  // The guessed types are heuristic, so only check the token of the first input
  const firstInput = decodedInputs[0];
  assert.equal(firstInput?.args[0].type, "address");
  assert.equal(firstInput?.args[0].value, USDC);
});

test("nested bytes without abi structure are not guessed as abi-encoded data", async () => {
  const bytes32 =
    "0x000000000000000000000000a0b86991c6218b36c1d19d4a2e9eb0ce3606eb48";
  const signature = `0x${"11".repeat(32)}${"22".repeat(32)}1b`;
  // Word-aligned, but guessed as fixed-size bytes only: a compact signature
  // or two hashes (bytes32,bytes32), a hash ending in a zero byte
  // (bytes32,bytes31), and a zero-padded packed swap path (bytes32,bytes11)
  const twoHashes = concat([keccak256("0x01"), keccak256("0x02")]);
  const hashEndingInZero = concat([
    keccak256("0x01"),
    padHex(keccak256("0x02").slice(0, 64) as `0x${string}`, {
      dir: "right",
      size: 32,
    }),
  ]);
  const packedPath = padHex(
    concat([`0x${"ab".repeat(20)}`, "0x000bb8", `0x${"cd".repeat(20)}`]),
    { dir: "right", size: 64 }
  );

  // The same single word is guessed as an address at the top level...
  assert.notEqual(await decodeWithSelector({ calldata: bytes32 }), null);
  // ...but not when it is nested inside another call.
  assert.equal(
    await decodeWithSelector({ calldata: bytes32, _depth: 1 }),
    null
  );
  assert.equal(
    await decodeWithSelector({ calldata: signature, _depth: 1 }),
    null
  );
  for (const calldata of [twoHashes, hashEndingInZero, packedPath]) {
    assert.equal(await decodeWithSelector({ calldata, _depth: 1 }), null);
  }
});
