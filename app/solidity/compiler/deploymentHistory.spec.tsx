function draft():DeploymentDraft {
  const contract={name:"Counter",sourcePath:"Counter.sol",abi:[{type:"constructor",inputs:[{name:"initial",type:"uint256"}],stateMutability:"payable"}],bytecode:"60006000",deployedBytecode:"00"};
  const content="contract Counter { constructor(uint initial) payable {} }";
  const sources={"Counter.sol":{content}};
  const build:CompilerBuild={input:{key:"build-key",workspaceId:"one",entry:"Counter.sol",entryId:"source",files:[{id:"source",name:"Counter.sol",content}],settings:{...DEFAULT_COMPILER_SETTINGS},sources,fingerprint:"exact-build"},result:{contracts:{"Counter.sol:Counter":contract}}};
  return {workspaceId:"one",build,contract,chainId:11155111,account,value:123n,args:[7n],data:`0x60006000${encodeAbiParameters([{type:"uint256"}],[7n]).slice(2)}`};
}
