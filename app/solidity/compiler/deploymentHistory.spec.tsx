it("retains an unsaved broadcast hash, warns before close, and retries storage without resending",async()=>{
  const {deploymentStore}=await import("@/lib/solidity/deployments");
  const {useDeploymentHistory}=await import("./useDeploymentHistory");
  const store={...deploymentStore,update:vi.fn(deploymentStore.update)};
  const receipt=vi.fn(()=>new Promise<never>(()=>{}));
  const hook=renderHook(()=>useDeploymentHistory("one",store,receipt));
  await waitFor(()=>expect(hook.result.current.ready).toBe(true));
  let record:any;
  await act(async()=>{const {workspaceId,...input}=draft();record=await hook.result.current.prepare(input);});
  store.update.mockRejectedValueOnce(new DOMException("Storage full","QuotaExceededError"));
  await act(async()=>{await expect(hook.result.current.update(record.id,{status:"pending",hash})).rejects.toThrow("Storage full");});
  expect(hook.result.current.records[0].hash).toBe(hash);expect(hook.result.current.hasUnsaved).toBe(true);
  const closing=new Event("beforeunload",{cancelable:true});window.dispatchEvent(closing);expect(closing.defaultPrevented).toBe(true);
  hook.unmount();
  const restored=renderHook(()=>useDeploymentHistory("one",store,receipt));
  await waitFor(()=>expect(restored.result.current.ready).toBe(true));
  expect(restored.result.current.hasUnsaved).toBe(true);
  expect(restored.result.current.records[0].hash).toBe(hash);
  await act(async()=>{await restored.result.current.retrySaving();});
  expect(restored.result.current.hasUnsaved).toBe(false);
  expect((await deploymentStore.list("one"))[0].hash).toBe(hash);
});
