it("persists verification checkpoints through hook remount and storage failure recovery",async()=>{
  const {deploymentStore}=await import("@/lib/solidity/deployments");
  const {useDeploymentHistory}=await import("./useDeploymentHistory");
  const record=await deploymentStore.prepare(draft());await deploymentStore.update(record.id,{status:"pending",hash});await deploymentStore.update(record.id,{status:"success",address});
  const store={...deploymentStore,update:vi.fn(deploymentStore.update)};
  const receipt=vi.fn();const hook=renderHook(()=>useDeploymentHistory("one",store,receipt));
  await waitFor(()=>expect(hook.result.current.ready).toBe(true));
  store.update.mockRejectedValueOnce(new Error("Storage full"));
  const progress={state:"pending" as const,guid:"guid",sourceId:"input",updatedAt:1};
  await act(async()=>{await expect(hook.result.current.saveVerification(record.id,"sourcify",progress)).rejects.toThrow("Storage full");});
  expect(hook.result.current.records[0].verification?.sourcify?.guid).toBe("guid");
  await act(async()=>{await hook.result.current.retrySaving();});
  hook.unmount();const restored=renderHook(()=>useDeploymentHistory("one",store,receipt));
  await waitFor(()=>expect(restored.result.current.ready).toBe(true));
  expect(restored.result.current.records[0].verification?.sourcify).toEqual(progress);
  expect(restored.result.current.hasUnsaved).toBe(false);expect(receipt).not.toHaveBeenCalled();
});
