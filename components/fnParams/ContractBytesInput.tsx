"use client";

import React, { useState } from "react";
import {
  Alert,
  AlertIcon,
  Box,
  Button,
  FormControl,
  FormLabel,
  Input,
  Modal,
  ModalOverlay,
  ModalContent,
  ModalHeader,
  ModalCloseButton,
  ModalBody,
  ModalFooter,
  Select,
  Text,
  VStack,
} from "@chakra-ui/react";
import type { JsonFragmentType } from "ethers";
import type { Hex } from "viem";
import { BytesInput } from "./inputs/BytesInput";
import {
  ManualParametersEditor,
  type ManualParam,
  prepareManualParams,
} from "@/components/calldata/ManualParametersEditor";
import {
  encodeStandard,
  encodeFunctionManual,
  type ManualParamType,
} from "@/lib/encoder";

// viem accepts an empty integer string as zero. Require an explicit base-unit value.
function validateBuilderValues(input: ManualParamType, value: unknown): void {
  const array = input.type.match(/^(.+)\[\d*\]$/);
  if (array && Array.isArray(value)) {
    value.forEach((item) =>
      validateBuilderValues({ ...input, type: array[1] }, item)
    );
  } else if (input.type === "tuple" && Array.isArray(value)) {
    input.components?.forEach((component, i) =>
      validateBuilderValues(component, value[i])
    );
  } else if (
    /^bytes(\d+)?$/.test(input.type) &&
    (typeof value !== "string" || !/^0x(?:[\da-f]{2})*$/i.test(value))
  ) {
    throw new Error(
      `Enter even-length 0x-prefixed hex for ${input.name || input.type}.`
    );
  } else if (
    /^u?int(\d+)?$/.test(input.type) &&
    !/^(?:-?\d+|0x[\da-f]+)$/i.test(String(value ?? ""))
  ) {
    throw new Error(
      `Enter an explicit integer in raw base units for ${input.name || input.type}.`
    );
  }
}

/** Opt-in contract wrapper. Shared BytesInput and encoder fields remain raw-only. */
export function ContractBytesInput({
  input,
  value,
  onChange,
  ...props
}: {
  input: JsonFragmentType;
  value: string;
  onChange: (e: React.ChangeEvent<HTMLInputElement>) => void;
  onKeyDown: (e: React.KeyboardEvent<HTMLInputElement>) => void;
  isInvalid: boolean;
}) {
  const [isOpen, setIsOpen] = useState(false);
  return (
    <Box>
      <BytesInput input={input} value={value} onChange={onChange} {...props} />
      <Button size="sm" variant="outline" onClick={() => setIsOpen(true)}>
        Build bytes{input.name ? `: ${input.name}` : ""}
      </Button>
      {isOpen && (
        <BytesBuilderDialog
          fieldName={input.name || "bytes"}
          onClose={() => setIsOpen(false)}
          onApply={(bytes) => {
            onChange({
              target: { value: bytes },
            } as React.ChangeEvent<HTMLInputElement>);
            setIsOpen(false);
          }}
        />
      )}
    </Box>
  );
}

function BytesBuilderDialog({
  fieldName,
  onClose,
  onApply,
}: {
  fieldName: string;
  onClose: () => void;
  onApply: (bytes: Hex) => void;
}) {
  const [mode, setMode] = useState("parameters");
  const [functionName, setFunctionName] = useState("");
  const [params, setParams] = useState<ManualParam[]>([
    { type: "uint256", name: "", value: "" },
  ]);
  const [result, setResult] = useState<Hex>();
  const [error, setError] = useState("");
  const invalidate = () => {
    setResult(undefined);
    setError("");
  };
  const generate = () => {
    setResult(undefined);
    setError("");
    try {
      if (
        mode === "function" &&
        !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(functionName.trim())
      ) {
        throw new Error(
          "Enter a function name (without parentheses or argument types)."
        );
      }
      const { types, values } = prepareManualParams(params);
      types.forEach((input, i) => validateBuilderValues(input, values[i]));
      setResult(
        mode === "function"
          ? encodeFunctionManual(functionName.trim(), types, values)
          : encodeStandard(
              types as Parameters<typeof encodeStandard>[0],
              values
            )
      );
    } catch (cause) {
      setError(
        cause instanceof Error
          ? cause.message
          : "Could not encode these parameters."
      );
    }
  };
  return (
    <Modal isOpen onClose={onClose} size="4xl" scrollBehavior="inside">
      <ModalOverlay />
      <ModalContent
        mx={{ base: 2, md: 4 }}
        maxW="min(56rem, calc(100vw - 1rem))"
      >
        <ModalHeader pr={12}>Build bytes for {fieldName}</ModalHeader>
        <ModalCloseButton />
        <ModalBody>
          <VStack align="stretch" spacing={4} minW={0}>
            <Text fontSize="sm">
              Local encoding only. Your raw field stays unchanged until you
              apply the generated bytes. Inner bytes fields accept raw hex;
              builders do not nest. Integers use exact raw base units (decimal
              or 0x), without unit conversion. Addresses must be raw hex; no ENS
              or address metadata lookups run in this builder.
            </Text>
            <FormControl>
              <FormLabel htmlFor="bytes-builder-mode">Payload format</FormLabel>
              <Select
                id="bytes-builder-mode"
                value={mode}
                onChange={(e) => {
                  invalidate();
                  setMode(e.target.value);
                }}
              >
                <option value="parameters">ABI parameters (no selector)</option>
                <option value="function">
                  Function calldata (selector + arguments)
                </option>
              </Select>
            </FormControl>
            {mode === "function" && (
              <FormControl>
                <FormLabel htmlFor="bytes-builder-name">
                  Function name
                </FormLabel>
                <Input
                  id="bytes-builder-name"
                  value={functionName}
                  placeholder="e.g. transfer"
                  onChange={(e) => {
                    invalidate();
                    setFunctionName(e.target.value);
                  }}
                />
              </FormControl>
            )}
            <ManualParametersEditor
              rawValues
              manualParams={params}
              setManualParams={(next) => {
                invalidate();
                setParams(next);
              }}
              encode={generate}
            />
            <Button onClick={generate}>Generate bytes</Button>
            {error && (
              <Alert status="error" alignItems="start">
                <AlertIcon />
                <Text whiteSpace="pre-wrap" overflowWrap="anywhere">
                  {error}
                </Text>
              </Alert>
            )}
            {result !== undefined && (
              <Box>
                <Text fontWeight="bold">
                  {mode === "function"
                    ? "Function calldata · selector + arguments"
                    : "ABI parameters · no selector"}
                </Text>
                <Text
                  as="pre"
                  fontSize="xs"
                  whiteSpace="pre-wrap"
                  overflowWrap="anywhere"
                  maxH="12rem"
                  overflowY="auto"
                  tabIndex={0}
                >
                  {result}
                </Text>
              </Box>
            )}
          </VStack>
        </ModalBody>
        <ModalFooter gap={3} flexWrap="wrap">
          <Button onClick={onClose}>Cancel</Button>
          <Button
            colorScheme="blue"
            isDisabled={result === undefined}
            onClick={() => {
              if (result !== undefined) onApply(result);
            }}
          >
            Apply bytes
          </Button>
        </ModalFooter>
      </ModalContent>
    </Modal>
  );
}
